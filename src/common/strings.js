const DICTS = { ar: AR, en: EN };

/** منشئ دالة ترجمة مرتبط بإعدادات التطبيق. */
function makeT(getLang) {
  return (key, vars) => {
    const lang = DICTS[getLang()] ? getLang() : 'ar';
    let s = DICTS[lang][key] || DICTS.ar[key] || key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

module.exports = { makeT, DICTS: { AR, EN } };
